// corpus.models.Origin.choices.
const ORIGIN_LABELS = { seed: 'Seed', generated: 'Generated', manual: 'Manual' };
const ORIGIN_STYLES = {
  seed: 'bg-blue-100 text-blue-700',
  generated: 'bg-purple-100 text-purple-700',
  manual: 'bg-gray-100 text-gray-700',
};

// Echoes corpus.permissions.ReadOnlyIfGenerated's own reasoning (its
// docstring: "Removing generated material is done by deleting the run that
// produced it... Deleting one row at a time would be selective reporting")
// and its `message` ("Generated material is immutable. Change the prompt or
// inputs and generate again, or delete the run that produced it.") - shown
// up front on every generated row, not only after a blocked PATCH, per the
// plan's "say why, rather than silently disabling a field."
const GENERATED_READONLY_NOTE =
  'Generated by a model, so it can’t be edited. Change the prompt or inputs and generate again, or delete the run that produced it.';

// Corpus rows now carry a read-only `generation_run` (the PhaseRun that
// produced them, or null) and a derived `is_scratch` (corpus/serializers.py,
// task 10.5): true for a row generated by an iterate-mode phase run - one
// with no `pipeline_run` of its own (spec §9). Before this, a scratch row
// looked exactly like a real run's own output everywhere except under
// `?phase_run=`, which is the one place the OLD phase-run lookup below
// could prove it. Marking it directly off the row itself is what makes
// this true wherever a corpus row appears - unfiltered Corpus, a
// `?run=`/`?origin=` filtered view, or any other screen that lists one -
// not only the one filter that happens to name the phase run explicitly.
const SCRATCH_READONLY_NOTE =
  'Made by a prompt test, not an experiment. Test output is never included in exports.';

function ScratchBadge({ generationRun }) {
  return (
    <span
      title="Made by a prompt test"
      className="inline-flex items-center rounded-full bg-amber-100 px-2.5 py-0.5 text-xs font-medium text-amber-800"
    >
      Test run
    </span>
  );
}

const SCENARIO_FIELDS = [
  ['actor', 'Actor'],
  ['trigger', 'Trigger'],
  ['standing_state', 'Standing state'],
  ['asset', 'Asset'],
  ['threat', 'Threat'],
  ['outcome', 'Outcome'],
  ['narrative', 'Narrative'],
];

// The card fields that are filled in, then the narrative, as one readable block.
function scenarioSummary(scenario) {
  const card = SCENARIO_FIELDS.filter(([key]) => key !== 'narrative' && scenario[key])
    .map(([key, label]) => `${label}: ${scenario[key]}`)
    .join('\n');
  return [card, scenario.narrative].filter(Boolean).join('\n\n');
}

function pick(source, keys) {
  return Object.fromEntries(keys.map((key) => [key, source[key] ?? '']));
}

function OriginBadge({ origin }) {
  return (
    <span
      className={`inline-flex items-center rounded-full px-2.5 py-0.5 text-xs font-medium ${
        ORIGIN_STYLES[origin] ?? 'bg-gray-100 text-gray-700'
      }`}
    >
      {ORIGIN_LABELS[origin] ?? origin}
    </span>
  );
}

// A labelled cluster of filter controls within the filter bar's second row
// (e.g. "Where it came from", "Run") - just a caption over a small grid, so
// related controls read as one group instead of seven look-alike boxes.
function FilterGroup({ caption, children }) {
  return (
    <div className="space-y-3 rounded-md border border-gray-200 bg-gray-50/60 p-3">
      <p className="text-xs font-semibold uppercase tracking-wide text-gray-500">{caption}</p>
      <div className="grid grid-cols-1 gap-3 sm:grid-cols-2">{children}</div>
    </div>
  );
}

const NATIVE_SELECT_CLASS = 'mt-1 block h-9 w-full rounded-md border border-gray-300 px-2 text-sm shadow-sm';

const emptyFilters = { origin: '', run: '', variant: '', phaseRun: '', system: '' };

// User feedback: "it makes sense only to show seed and manual; the
// generated ones are accessible from their runs" - generated rows stay
// hidden unless this is on (default off). Origin/run/variant only ever
// narrow WITHIN whatever this toggle already includes.
const DEFAULT_INCLUDE_GENERATED = false;

// `?origin=&run=&variant=&phase_run=` apply to both system descriptions and
// scenarios; `?system=` exists only on the scenarios endpoint (spec §9).
function buildParams(filters, { includeSystem }) {
  const params = {};
  // The two "generated — …" choices narrow further client-side, on `is_scratch`.
  if (filters.origin) params.origin = filters.origin.startsWith('generated') ? 'generated' : filters.origin;
  if (filters.run) params.run = filters.run;
  if (filters.variant) params.variant = filters.variant;
  if (filters.phaseRun) params.phase_run = filters.phaseRun;
  if (includeSystem && filters.system) params.system = filters.system;
  return params;
}

function byId(data) {
  return new Map((data?.results ?? []).map((row) => [row.id, row]));
}

// Newest-first: finished (falling back to started) timestamp, then id as a
// stable tiebreak for rows sharing a timestamp.
function byRecency(a, b) {
  return (b.finished_at ?? b.started_at ?? '').localeCompare(a.finished_at ?? a.started_at ?? '') || b.id - a.id;
}

// Scratch output goes by deleting the whole test run that produced it, never
// row by row; the confirmation says so.
function DeleteScratchRunButton({ phaseRunId }) {
  const deletePhaseRun = useDeletePhaseRun();
  const [confirming, setConfirming] = useState(false);

  if (!confirming) {
    return (
      <button
        type="button"
        onClick={() => setConfirming(true)}
        className="rounded-md border border-red-300 px-2 py-1 text-xs font-medium text-red-700 hover:bg-red-50"
      >
        Delete
      </button>
    );
  }
  return (
    <Modal title="Delete this test run?" onClose={() => setConfirming(false)}>
      <div className="space-y-3 text-sm text-gray-700">
        <p>
          This deletes the test run and <strong>every system and scenario it generated</strong>, not only this
          row, plus its recorded model calls. It cannot be undone.
        </p>
        {deletePhaseRun.isError && <ErrorBanner error={deletePhaseRun.error} />}
        <div className="flex justify-end gap-2">
          <button
            type="button"
            onClick={() => setConfirming(false)}
            className="rounded-md border border-gray-300 px-3 py-1.5 text-sm font-medium text-gray-700 hover:bg-gray-100"
          >
            Cancel
          </button>
          <button
            type="button"
            disabled={deletePhaseRun.isPending}
            onClick={async () => {
              try {
                await deletePhaseRun.mutateAsync(phaseRunId);
              } catch {
                // Shown above via deletePhaseRun.error.
              }
            }}
            className="rounded-md bg-red-600 px-3 py-1.5 text-sm font-medium text-white hover:bg-red-700 disabled:opacity-60"
          >
            {deletePhaseRun.isPending ? 'Deleting…' : 'Delete test run'}
          </button>
        </div>
      </div>
    </Modal>
  );
}

function SystemDescriptionRow({ system }) {
  const updateSystem = useUpdateSystemDescription();
  const [editing, setEditing] = useState(false);
  // Seeded fresh from `system` the moment "Edit" is clicked (below), rather
  // than mirrored from it via an effect: this is a plain local draft, only
  // ever read while `editing` is true, so there is nothing to keep
  // synchronized with the prop between edits - just the freshest value at
  // the moment editing starts.
  const [title, setTitle] = useState(system.title);
  const [body, setBody] = useState(system.body);

  function startEditing() {
    setTitle(system.title);
    setBody(system.body);
    setEditing(true);
  }

  async function handleSave(event) {
    event.preventDefault();
    try {
      await updateSystem.mutateAsync({ id: system.id, title, body });
      setEditing(false);
    } catch {
      // Surfaced below via updateSystem.isError/error.
    }
  }

  return (
    <li className="space-y-2 px-4 py-3">
      <div className="flex items-center justify-between gap-3">
        <p className="text-sm font-semibold text-gray-900">{system.title}</p>
        <div className="flex shrink-0 items-center gap-2">
          <OriginBadge origin={system.origin} />
          {system.is_scratch && <ScratchBadge generationRun={system.generation_run} />}
          {system.origin === 'generated' && <GenerationProvenance phaseRunId={system.generation_run} />}
          {system.is_scratch && <DeleteScratchRunButton phaseRunId={system.generation_run} />}
          {system.is_editable && !editing && (
            <button
              type="button"
              onClick={startEditing}
              className="rounded-md border border-gray-300 px-2 py-1 text-xs font-medium text-gray-700 hover:bg-gray-100"
            >
              Edit
            </button>
          )}
        </div>
      </div>

      {!system.is_editable && <p className="text-xs text-gray-500">{GENERATED_READONLY_NOTE}</p>}
      {system.is_scratch && (
        <p className="text-xs font-medium text-amber-800">
          {SCRATCH_READONLY_NOTE}
        </p>
      )}

      {!editing && (
        <CollapsibleText text={system.body} empty="(no body yet)" mono={false} />
      )}

      {editing && (
        <form onSubmit={handleSave} className="space-y-2">
          <div>
            <label htmlFor={`title-${system.id}`} className="block text-xs font-medium text-gray-700">
              Title
            </label>
            <input
              id={`title-${system.id}`}
              value={title}
              onChange={(event) => setTitle(event.target.value)}
              className="mt-1 block w-full rounded-md border border-gray-300 px-3 py-1.5 text-sm shadow-sm"
            />
          </div>
          <div>
            <label htmlFor={`body-${system.id}`} className="block text-xs font-medium text-gray-700">
              Body
            </label>
            <textarea
              id={`body-${system.id}`}
              value={body}
              onChange={(event) => setBody(event.target.value)}
              rows={3}
              className="mt-1 block w-full rounded-md border border-gray-300 px-3 py-1.5 text-sm shadow-sm"
            />
          </div>
          {updateSystem.isError && <ErrorBanner error={updateSystem.error} />}
          <div className="flex gap-2">
            <button
              type="submit"
              disabled={updateSystem.isPending}
              className="rounded-md bg-brand-600 px-3 py-1.5 text-xs font-medium text-white hover:bg-brand-700 disabled:cursor-not-allowed disabled:opacity-60"
            >
              {updateSystem.isPending ? 'Saving…' : 'Save'}
            </button>
            <button
              type="button"
              onClick={() => {
                setTitle(system.title);
                setBody(system.body);
                setEditing(false);
              }}
              className="rounded-md border border-gray-300 px-3 py-1.5 text-xs font-medium text-gray-700 hover:bg-gray-100"
            >
              Cancel
            </button>
          </div>
        </form>
      )}
    </li>
  );
}

function ScenarioRow({ scenario, systemTitle }) {
  const updateScenario = useUpdateScenario();
  const [editing, setEditing] = useState(false);
  // Same reasoning as SystemDescriptionRow's `title`/`body`: a local draft
  // seeded fresh from `scenario` when "Edit" is clicked, not mirrored via an
  // effect - it is only ever read while `editing` is true.
  const [values, setValues] = useState(() => pick(scenario, SCENARIO_FIELDS.map(([key]) => key)));

  function startEditing() {
    setValues(pick(scenario, SCENARIO_FIELDS.map(([key]) => key)));
    setEditing(true);
  }

  async function handleSave(event) {
    event.preventDefault();
    try {
      await updateScenario.mutateAsync({ id: scenario.id, ...values });
      setEditing(false);
    } catch {
      // Surfaced below via updateScenario.isError/error.
    }
  }

  return (
    <li className="space-y-2 px-4 py-3">
      <div className="flex items-center justify-between gap-3">
        <p className="text-sm font-semibold text-gray-900">
          {systemTitle} / {scenario.scenario_id}
        </p>
        <div className="flex shrink-0 items-center gap-2">
          <OriginBadge origin={scenario.origin} />
          {scenario.is_scratch && <ScratchBadge generationRun={scenario.generation_run} />}
          {scenario.origin === 'generated' && <GenerationProvenance phaseRunId={scenario.generation_run} />}
          {scenario.is_scratch && <DeleteScratchRunButton phaseRunId={scenario.generation_run} />}
          {scenario.is_editable && !editing && (
            <button
              type="button"
              onClick={startEditing}
              className="rounded-md border border-gray-300 px-2 py-1 text-xs font-medium text-gray-700 hover:bg-gray-100"
            >
              Edit
            </button>
          )}
        </div>
      </div>

      {!scenario.is_editable && <p className="text-xs text-gray-500">{GENERATED_READONLY_NOTE}</p>}
      {scenario.is_scratch && (
        <p className="text-xs font-medium text-amber-800">
          {SCRATCH_READONLY_NOTE}
        </p>
      )}

      {!editing && (
        <CollapsibleText text={scenarioSummary(scenario)} empty="(empty scenario)" mono={false} />
      )}

      {editing && (
        <form onSubmit={handleSave} className="space-y-2">
          {SCENARIO_FIELDS.map(([field, label]) => (
            <div key={field}>
              <label htmlFor={`${field}-${scenario.id}`} className="block text-xs font-medium text-gray-700">
                {label}
              </label>
              <textarea
                id={`${field}-${scenario.id}`}
                value={values[field]}
                onChange={(event) => setValues((current) => ({ ...current, [field]: event.target.value }))}
                rows={field === 'narrative' ? 3 : 1}
                className="mt-1 block w-full rounded-md border border-gray-300 px-3 py-1.5 text-sm shadow-sm"
              />
            </div>
          ))}
          {updateScenario.isError && <ErrorBanner error={updateScenario.error} />}
          <div className="flex gap-2">
            <button
              type="submit"
              disabled={updateScenario.isPending}
              className="rounded-md bg-brand-600 px-3 py-1.5 text-xs font-medium text-white hover:bg-brand-700 disabled:cursor-not-allowed disabled:opacity-60"
            >
              {updateScenario.isPending ? 'Saving…' : 'Save'}
            </button>
            <button
              type="button"
              onClick={() => {
                setValues(pick(scenario, SCENARIO_FIELDS.map(([key]) => key)));
                setEditing(false);
              }}
              className="rounded-md border border-gray-300 px-3 py-1.5 text-xs font-medium text-gray-700 hover:bg-gray-100"
            >
              Cancel
            </button>
          </div>
        </form>
      )}
    </li>
  );
}

export default function Corpus() {
  const { isStaff } = useAuth();
  const [filters, setFilters] = useState(emptyFilters);
  const [searchInput, setSearchInput] = useState('');
  const [search, setSearch] = useState('');
  const [confirmingDeletePhaseRun, setConfirmingDeletePhaseRun] = useState(false);
  const [includeGenerated, setIncludeGenerated] = useState(DEFAULT_INCLUDE_GENERATED);
  const deletePhaseRun = useDeletePhaseRun();

  // The only debounced control - the selects below apply on the fly, but a
  // keystroke in the search box shouldn't re-filter on every character.
  useEffect(() => {
    const timer = setTimeout(() => setSearch(searchInput), 300);
    return () => clearTimeout(timer);
  }, [searchInput]);

  function handleClear() {
    setFilters(emptyFilters);
    setSearchInput('');
    setSearch('');
    setIncludeGenerated(DEFAULT_INCLUDE_GENERATED);
  }

  // Turning generated rows off also drops the filters that only ever apply
  // to them (Run/Generation run/Variant) - keeping a hidden filter selected
  // would silently narrow nothing once its own controls are gone. A
  // generated-only Origin choice falls back to "All origins" for the same
  // reason; Seed/Manual stay exactly as chosen.
  function handleIncludeGeneratedChange(checked) {
    setIncludeGenerated(checked);
    if (!checked) {
      setFilters((current) => ({
        ...current,
        run: '',
        phaseRun: '',
        variant: '',
        origin: current.origin === 'seed' || current.origin === 'manual' ? current.origin : '',
      }));
    }
  }

  const systemsQuery = useSystemDescriptions(buildParams(filters, { includeSystem: false }));
  const scenariosQuery = useScenarios(buildParams(filters, { includeSystem: true }));
  // Unfiltered - the "System" picker offers every system regardless of what
  // else is selected, so picking one never depends on the other filters.
  const systemOptionsQuery = useSystemDescriptions();

  const phaseRunId = filters.phaseRun ? Number(filters.phaseRun) : null;
  const phaseRunQuery = usePhaseRun(phaseRunId);

  // Options for the "Experiment run" and "Generation run" selects - both
  // fields (and what they back) only matter once generated rows are
  // included, so there is nothing to fetch until then.
  const pipelineRunsQuery = usePipelineRuns({}, { enabled: includeGenerated });
  const experimentsQuery = useExperiments({}, { enabled: includeGenerated });
  const generationRunsQuery = usePhaseRuns({ phase: 2 }, { enabled: includeGenerated });
  const promptsQuery = usePromptTemplates({ phase: 2 }, { enabled: includeGenerated });
  const pipelineRunsById = byId(pipelineRunsQuery.data);
  const experimentsById = byId(experimentsQuery.data);
  const promptsById = byId(promptsQuery.data);

  const experimentRunOptions = [...(pipelineRunsQuery.data?.results ?? [])].sort(byRecency).map((run) => ({
    value: String(run.id),
    label: `${experimentsById.get(run.experiment)?.name ?? 'Experiment'} · repetition ${run.repetition_index}`,
  }));

  // Same label shape as ScenarioPicker's own run groups (components/
  // ScenarioPicker.jsx's useScenarioGroups): "<experiment> · repetition N"
  // for an experiment-launched run, "Prompt test" for an ad-hoc one, then
  // variant/prompt/model/finished-date as further detail.
  const generationRunOptions = [...(generationRunsQuery.data?.results ?? [])].sort(byRecency).map((run) => {
    const prompt = promptsById.get(run.prompt_template);
    const repetition = run.pipeline_run ? pipelineRunsById.get(run.pipeline_run) : null;
    const experiment = repetition ? experimentsById.get(repetition.experiment) : null;
    const head = run.pipeline_run
      ? `${experiment?.name ?? 'Experiment'} · repetition ${repetition?.repetition_index ?? '…'}`
      : 'Prompt test';
    const details = [
      run.variant ? `Variant ${run.variant}` : '',
      prompt ? `${prompt.name} v${prompt.version}` : '',
      run.model,
      run.finished_at ? new Date(run.finished_at).toLocaleString() : '',
    ].filter(Boolean);
    return { value: String(run.id), label: [head, ...details].join(' · ') };
  });

  // Generated systems are excluded here too while hidden - offering one as
  // a "System (scenarios)" choice would only ever show zero rows.
  const systemOptions = [...(systemOptionsQuery.data?.results ?? [])]
    .filter((system) => includeGenerated || system.origin !== 'generated')
    .sort((a, b) => a.title.localeCompare(b.title));

  // Iterate-mode phase runs are ad-hoc: `pipeline_run` is null (spec §5.4).
  // Corpus rows now carry their own `is_scratch` directly (task 10.5, see
  // `ScratchBadge`/`SCRATCH_READONLY_NOTE` above), so this banner is no
  // longer the only way to learn a filtered view is scratch material - but
  // it is still the one place this screen can say so even when the
  // `?phase_run=` filter matches NO rows yet (an iterate run that hasn't
  // generated anything, or generated nothing matching the other filters),
  // and it is what backs the delete-this-run action below.
  const isScratch = phaseRunId != null && phaseRunQuery.isSuccess && phaseRunQuery.data.pipeline_run == null;

  const scratchOnly = { 'generated-scratch': true, 'generated-experiment': false }[filters.origin];
  const matchesScratch = (row) => scratchOnly === undefined || row.is_scratch === scratchOnly;
  // The toggle's own exclusion - client-side, so the headings' counts below
  // always match exactly what is actually shown, regardless of what the
  // API itself was asked to filter by.
  const matchesIncludeGenerated = (row) => includeGenerated || row.origin !== 'generated';
  const searchWords = search.toLowerCase().split(/\s+/).filter(Boolean);
  const matchesSearch = (text) => searchWords.every((word) => text.includes(word));

  const allSystems = (systemsQuery.data?.results ?? []).filter(matchesScratch).filter(matchesIncludeGenerated);
  const allScenarios = (scenariosQuery.data?.results ?? []).filter(matchesScratch).filter(matchesIncludeGenerated);
  const systemTitleById = new Map(allSystems.map((system) => [system.id, system.title]));

  const systems = allSystems.filter((system) => matchesSearch(`${system.title} ${system.body}`.toLowerCase()));
  const scenarios = allScenarios.filter((scenario) => {
    const systemTitle = systemTitleById.get(scenario.system_description) ?? '';
    const text = [systemTitle, scenario.scenario_id, ...SCENARIO_FIELDS.map(([key]) => scenario[key])]
      .filter(Boolean)
      .join(' ')
      .toLowerCase();
    return matchesSearch(text);
  });

  async function handleDeletePhaseRunConfirmed() {
    try {
      await deletePhaseRun.mutateAsync(phaseRunId);
      setConfirmingDeletePhaseRun(false);
      // The filter named a phase run that no longer exists - clear it
      // rather than leave the filter pointed at a dangling id.
      setFilters((current) => ({ ...current, phaseRun: '' }));
    } catch {
      // Surfaced below via deletePhaseRun.isError/error - dialog stays open
      // so the API's own 409 message (e.g. "run_in_flight") is visible.
    }
  }

  return (
    <div className="space-y-8">
      <div role="group" aria-label="Corpus filters" className="space-y-4 rounded-lg border border-gray-200 bg-white p-4">
        <div className="flex flex-col gap-3 sm:flex-row sm:items-end">
          <div className="flex-1">
            <label htmlFor="filter-search" className="block text-xs font-medium text-gray-700">
              Search
            </label>
            <input
              id="filter-search"
              type="search"
              value={searchInput}
              onChange={(event) => setSearchInput(event.target.value)}
              placeholder="Title, body, scenario text…"
              className={NATIVE_SELECT_CLASS}
            />
          </div>
          <button
            type="button"
            onClick={handleClear}
            className="h-9 shrink-0 rounded-md border border-gray-300 px-3 text-sm font-medium text-gray-700 hover:bg-gray-100"
          >
            Clear
          </button>
        </div>

        <label htmlFor="filter-include-generated" className="flex items-center gap-2 text-sm text-gray-700">
          <input
            id="filter-include-generated"
            type="checkbox"
            checked={includeGenerated}
            onChange={(event) => handleIncludeGeneratedChange(event.target.checked)}
          />
          Include generated systems and scenarios
        </label>

        <div className={`grid grid-cols-1 gap-4 ${includeGenerated ? 'sm:grid-cols-3' : 'sm:grid-cols-2'}`}>
          <FilterGroup caption="Where it came from">
            <div>
              <label htmlFor="filter-origin" className="block text-xs font-medium text-gray-700">
                Origin
              </label>
              <select
                id="filter-origin"
                value={filters.origin}
                onChange={(event) => setFilters((current) => ({ ...current, origin: event.target.value }))}
                className={NATIVE_SELECT_CLASS}
              >
                <option value="">All origins</option>
                <option value="seed">Seed</option>
                {includeGenerated && <option value="generated">Generated — all</option>}
                {includeGenerated && <option value="generated-experiment">Generated — experiment runs</option>}
                {includeGenerated && <option value="generated-scratch">Generated — prompt tests</option>}
                <option value="manual">Manual</option>
              </select>
            </div>
            {includeGenerated && (
              <div>
                <label htmlFor="filter-variant" className="block text-xs font-medium text-gray-700">
                  Variant
                </label>
                <select
                  id="filter-variant"
                  value={filters.variant}
                  onChange={(event) => setFilters((current) => ({ ...current, variant: event.target.value }))}
                  className={NATIVE_SELECT_CLASS}
                >
                  <option value="">All variants</option>
                  <option value="A">A</option>
                  <option value="B">B</option>
                </select>
              </div>
            )}
          </FilterGroup>

          {includeGenerated && (
            <FilterGroup caption="Run">
              <SearchableSelect
                id="filter-run"
                label="Experiment run"
                value={filters.run}
                onChange={(value) => {
                  setFilters((current) => ({ ...current, run: value }));
                  if (value) setIncludeGenerated(true);
                }}
                options={experimentRunOptions}
                emptyLabel="All experiment runs"
              />
              <SearchableSelect
                id="filter-phase-run"
                label="Generation run"
                value={filters.phaseRun}
                onChange={(value) => {
                  setFilters((current) => ({ ...current, phaseRun: value }));
                  if (value) setIncludeGenerated(true);
                }}
                options={generationRunOptions}
                emptyLabel="All generation runs"
              />
            </FilterGroup>
          )}

          <FilterGroup caption="System">
            <SearchableSelect
              id="filter-system"
              label="System (scenarios)"
              value={filters.system}
              onChange={(value) => setFilters((current) => ({ ...current, system: value }))}
              options={systemOptions.map((system) => ({ value: String(system.id), label: system.title }))}
              emptyLabel="All systems"
            />
          </FilterGroup>
        </div>
      </div>

      {phaseRunId != null && phaseRunQuery.isError && <ErrorBanner error={phaseRunQuery.error} />}
      {(pipelineRunsQuery.isError || experimentsQuery.isError || generationRunsQuery.isError || promptsQuery.isError) && (
        <ErrorBanner
          error={pipelineRunsQuery.error || experimentsQuery.error || generationRunsQuery.error || promptsQuery.error}
        />
      )}
      {isScratch && (
        <div className="space-y-3">
          <div role="status" className="rounded-md border border-amber-300 bg-amber-50 px-4 py-3 text-sm text-amber-800">
            This is the output of a prompt test, not an experiment. Test output is never included in
            exports.
          </div>
          {isStaff && !confirmingDeletePhaseRun && (
            <button
              type="button"
              onClick={() => setConfirmingDeletePhaseRun(true)}
              className="rounded-md border border-red-600 px-3 py-1.5 text-sm font-medium text-red-700 hover:bg-red-50"
            >
              Delete this run
            </button>
          )}
          {confirmingDeletePhaseRun && (
            <ConfirmDialog
              title="Delete this test run?"
              message="Its generated material — every system description and scenario it produced — goes with it. There is no per-row undo."
              confirmLabel="Confirm"
              cancelLabel="Never mind"
              pending={deletePhaseRun.isPending}
              onConfirm={handleDeletePhaseRunConfirmed}
              onCancel={() => setConfirmingDeletePhaseRun(false)}
            />
          )}
          {deletePhaseRun.isError && <ErrorBanner error={deletePhaseRun.error} />}
        </div>
      )}

      <section aria-labelledby="systems-heading" className="space-y-3">
        <h2 id="systems-heading" className="text-lg font-medium text-gray-900">
          System descriptions
          {systemsQuery.isSuccess && <span aria-hidden="true" className="ml-2 text-sm font-normal text-gray-400">({systems.length})</span>}
        </h2>

        {systemsQuery.isLoading && <p className="text-sm text-gray-500">Loading system descriptions…</p>}
        {systemsQuery.isError && <ErrorBanner error={systemsQuery.error} />}

        {systemsQuery.isSuccess && systems.length === 0 && (
          <EmptyState title="No system descriptions match" message="Try clearing or widening the filters above." />
        )}

        {systemsQuery.isSuccess && systems.length > 0 && (
          <ul className="max-h-[36rem] overflow-y-auto divide-y divide-gray-200 rounded-lg border border-gray-200 bg-white">
            {systems.map((system) => (
              <SystemDescriptionRow key={system.id} system={system} />
            ))}
          </ul>
        )}
      </section>

      <section aria-labelledby="scenarios-heading" className="space-y-3">
        <h2 id="scenarios-heading" className="text-lg font-medium text-gray-900">
          Scenarios
          {scenariosQuery.isSuccess && <span aria-hidden="true" className="ml-2 text-sm font-normal text-gray-400">({scenarios.length})</span>}
        </h2>

        {scenariosQuery.isLoading && <p className="text-sm text-gray-500">Loading scenarios…</p>}
        {scenariosQuery.isError && <ErrorBanner error={scenariosQuery.error} />}

        {scenariosQuery.isSuccess && scenarios.length === 0 && (
          <EmptyState title="No scenarios match" message="Try clearing or widening the filters above." />
        )}

        {scenariosQuery.isSuccess && scenarios.length > 0 && (
          <ul className="max-h-[36rem] overflow-y-auto divide-y divide-gray-200 rounded-lg border border-gray-200 bg-white">
            {scenarios.map((scenario) => (
              <ScenarioRow
                key={scenario.id}
                scenario={scenario}
                systemTitle={systemTitleById.get(scenario.system_description) ?? `System #${scenario.system_description}`}
              />
            ))}
          </ul>
        )}
      </section>
    </div>
  );
}
