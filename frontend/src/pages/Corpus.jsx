import { useState } from 'react';
import { useAuth } from '../contexts/auth-context';
import {
  useDeletePhaseRun,
  usePhaseRun,
  useScenarios,
  useSystemDescriptions,
  useUpdateScenario,
  useUpdateSystemDescription,
} from '../api/queries';
import ConfirmDialog from '../components/ConfirmDialog';
import EmptyState from '../components/EmptyState';
import ErrorBanner from '../components/ErrorBanner';

// corpus.models.Origin.choices.
const ORIGIN_LABELS = { seed: 'Seed', generated: 'Generated', manual: 'Manual' };
const ORIGIN_STYLES = {
  seed: 'bg-blue-100 text-blue-700',
  generated: 'bg-purple-100 text-purple-700',
  manual: 'bg-gray-100 text-gray-700',
};

// Echoes corpus.permissions.ReadOnlyIfGenerated's own reasoning (its
// docstring: "Removing generated material is done by deleting the run that
// produced it... Deleting one row at a time would be selective reporting")
// and its `message` ("Generated material is immutable. Change the prompt or
// inputs and generate again, or delete the run that produced it.") - shown
// up front on every generated row, not only after a blocked PATCH, per the
// plan's "say why, rather than silently disabling a field."
const GENERATED_READONLY_NOTE =
  'Generated by a run — immutable. Change the prompt or inputs and generate again, or delete the run that produced it.';

// Corpus rows now carry a read-only `generation_run` (the PhaseRun that
// produced them, or null) and a derived `is_scratch` (corpus/serializers.py,
// task 10.5): true for a row generated by an iterate-mode phase run - one
// with no `pipeline_run` of its own (spec §9). Before this, a scratch row
// looked exactly like a real run's own output everywhere except under
// `?phase_run=`, which is the one place the OLD phase-run lookup below
// could prove it. Marking it directly off the row itself is what makes
// this true wherever a corpus row appears - unfiltered Corpus, a
// `?run=`/`?origin=` filtered view, or any other screen that lists one -
// not only the one filter that happens to name the phase run explicitly.
const SCRATCH_READONLY_NOTE =
  'Scratch — generated by an iterate run (phase run #%ID%), not any launched experiment. Never archived, never included in any export.';

function ScratchBadge({ generationRun }) {
  return (
    <span
      title={`Scratch material from iterate-mode phase run #${generationRun}`}
      className="inline-flex items-center rounded-full bg-amber-100 px-2.5 py-0.5 text-xs font-medium text-amber-800"
    >
      Scratch
    </span>
  );
}

const SCENARIO_FIELDS = [
  ['actor', 'Actor'],
  ['trigger', 'Trigger'],
  ['standing_state', 'Standing state'],
  ['asset', 'Asset'],
  ['threat', 'Threat'],
  ['outcome', 'Outcome'],
  ['narrative', 'Narrative'],
];

function pick(source, keys) {
  return Object.fromEntries(keys.map((key) => [key, source[key] ?? '']));
}

function OriginBadge({ origin }) {
  return (
    <span
      className={`inline-flex items-center rounded-full px-2.5 py-0.5 text-xs font-medium ${
        ORIGIN_STYLES[origin] ?? 'bg-gray-100 text-gray-700'
      }`}
    >
      {ORIGIN_LABELS[origin] ?? origin}
    </span>
  );
}

const emptyFilters = { origin: '', run: '', variant: '', phaseRun: '', system: '' };

// `?origin=&run=&variant=&phase_run=` apply to both system descriptions and
// scenarios; `?system=` exists only on the scenarios endpoint (spec §9).
function buildParams(filters, { includeSystem }) {
  const params = {};
  if (filters.origin) params.origin = filters.origin;
  if (filters.run) params.run = filters.run;
  if (filters.variant) params.variant = filters.variant;
  if (filters.phaseRun) params.phase_run = filters.phaseRun;
  if (includeSystem && filters.system) params.system = filters.system;
  return params;
}

function SystemDescriptionRow({ system }) {
  const updateSystem = useUpdateSystemDescription();
  const [editing, setEditing] = useState(false);
  // Seeded fresh from `system` the moment "Edit" is clicked (below), rather
  // than mirrored from it via an effect: this is a plain local draft, only
  // ever read while `editing` is true, so there is nothing to keep
  // synchronized with the prop between edits - just the freshest value at
  // the moment editing starts.
  const [title, setTitle] = useState(system.title);
  const [body, setBody] = useState(system.body);

  function startEditing() {
    setTitle(system.title);
    setBody(system.body);
    setEditing(true);
  }

  async function handleSave(event) {
    event.preventDefault();
    try {
      await updateSystem.mutateAsync({ id: system.id, title, body });
      setEditing(false);
    } catch {
      // Surfaced below via updateSystem.isError/error.
    }
  }

  return (
    <li className="space-y-2 px-4 py-3">
      <div className="flex items-center justify-between gap-3">
        <p className="text-sm font-semibold text-gray-900">{system.title}</p>
        <div className="flex shrink-0 items-center gap-2">
          <OriginBadge origin={system.origin} />
          {system.is_scratch && <ScratchBadge generationRun={system.generation_run} />}
          {system.is_editable && !editing && (
            <button
              type="button"
              onClick={startEditing}
              className="rounded-md border border-gray-300 px-2 py-1 text-xs font-medium text-gray-700 hover:bg-gray-100"
            >
              Edit
            </button>
          )}
        </div>
      </div>

      {!system.is_editable && <p className="text-xs text-gray-500">{GENERATED_READONLY_NOTE}</p>}
      {system.is_scratch && (
        <p className="text-xs font-medium text-amber-800">
          {SCRATCH_READONLY_NOTE.replace('%ID%', system.generation_run)}
        </p>
      )}

      {!editing && (
        <p className="whitespace-pre-wrap text-sm text-gray-600">{system.body || '(no body yet)'}</p>
      )}

      {editing && (
        <form onSubmit={handleSave} className="space-y-2">
          <div>
            <label htmlFor={`title-${system.id}`} className="block text-xs font-medium text-gray-700">
              Title
            </label>
            <input
              id={`title-${system.id}`}
              value={title}
              onChange={(event) => setTitle(event.target.value)}
              className="mt-1 block w-full rounded-md border border-gray-300 px-3 py-1.5 text-sm shadow-sm"
            />
          </div>
          <div>
            <label htmlFor={`body-${system.id}`} className="block text-xs font-medium text-gray-700">
              Body
            </label>
            <textarea
              id={`body-${system.id}`}
              value={body}
              onChange={(event) => setBody(event.target.value)}
              rows={3}
              className="mt-1 block w-full rounded-md border border-gray-300 px-3 py-1.5 text-sm shadow-sm"
            />
          </div>
          {updateSystem.isError && <ErrorBanner error={updateSystem.error} />}
          <div className="flex gap-2">
            <button
              type="submit"
              disabled={updateSystem.isPending}
              className="rounded-md bg-brand-600 px-3 py-1.5 text-xs font-medium text-white hover:bg-brand-700 disabled:cursor-not-allowed disabled:opacity-60"
            >
              {updateSystem.isPending ? 'Saving…' : 'Save'}
            </button>
            <button
              type="button"
              onClick={() => {
                setTitle(system.title);
                setBody(system.body);
                setEditing(false);
              }}
              className="rounded-md border border-gray-300 px-3 py-1.5 text-xs font-medium text-gray-700 hover:bg-gray-100"
            >
              Cancel
            </button>
          </div>
        </form>
      )}
    </li>
  );
}

function ScenarioRow({ scenario, systemTitle }) {
  const updateScenario = useUpdateScenario();
  const [editing, setEditing] = useState(false);
  // Same reasoning as SystemDescriptionRow's `title`/`body`: a local draft
  // seeded fresh from `scenario` when "Edit" is clicked, not mirrored via an
  // effect - it is only ever read while `editing` is true.
  const [values, setValues] = useState(() => pick(scenario, SCENARIO_FIELDS.map(([key]) => key)));

  function startEditing() {
    setValues(pick(scenario, SCENARIO_FIELDS.map(([key]) => key)));
    setEditing(true);
  }

  async function handleSave(event) {
    event.preventDefault();
    try {
      await updateScenario.mutateAsync({ id: scenario.id, ...values });
      setEditing(false);
    } catch {
      // Surfaced below via updateScenario.isError/error.
    }
  }

  return (
    <li className="space-y-2 px-4 py-3">
      <div className="flex items-center justify-between gap-3">
        <p className="text-sm font-semibold text-gray-900">
          {systemTitle} / {scenario.scenario_id}
        </p>
        <div className="flex shrink-0 items-center gap-2">
          <OriginBadge origin={scenario.origin} />
          {scenario.is_scratch && <ScratchBadge generationRun={scenario.generation_run} />}
          {scenario.is_editable && !editing && (
            <button
              type="button"
              onClick={startEditing}
              className="rounded-md border border-gray-300 px-2 py-1 text-xs font-medium text-gray-700 hover:bg-gray-100"
            >
              Edit
            </button>
          )}
        </div>
      </div>

      {!scenario.is_editable && <p className="text-xs text-gray-500">{GENERATED_READONLY_NOTE}</p>}
      {scenario.is_scratch && (
        <p className="text-xs font-medium text-amber-800">
          {SCRATCH_READONLY_NOTE.replace('%ID%', scenario.generation_run)}
        </p>
      )}

      {!editing && (
        <p className="whitespace-pre-wrap text-sm text-gray-600">
          {scenario.narrative || '(no narrative yet)'}
        </p>
      )}

      {editing && (
        <form onSubmit={handleSave} className="space-y-2">
          {SCENARIO_FIELDS.map(([field, label]) => (
            <div key={field}>
              <label htmlFor={`${field}-${scenario.id}`} className="block text-xs font-medium text-gray-700">
                {label}
              </label>
              <textarea
                id={`${field}-${scenario.id}`}
                value={values[field]}
                onChange={(event) => setValues((current) => ({ ...current, [field]: event.target.value }))}
                rows={field === 'narrative' ? 3 : 1}
                className="mt-1 block w-full rounded-md border border-gray-300 px-3 py-1.5 text-sm shadow-sm"
              />
            </div>
          ))}
          {updateScenario.isError && <ErrorBanner error={updateScenario.error} />}
          <div className="flex gap-2">
            <button
              type="submit"
              disabled={updateScenario.isPending}
              className="rounded-md bg-brand-600 px-3 py-1.5 text-xs font-medium text-white hover:bg-brand-700 disabled:cursor-not-allowed disabled:opacity-60"
            >
              {updateScenario.isPending ? 'Saving…' : 'Save'}
            </button>
            <button
              type="button"
              onClick={() => {
                setValues(pick(scenario, SCENARIO_FIELDS.map(([key]) => key)));
                setEditing(false);
              }}
              className="rounded-md border border-gray-300 px-3 py-1.5 text-xs font-medium text-gray-700 hover:bg-gray-100"
            >
              Cancel
            </button>
          </div>
        </form>
      )}
    </li>
  );
}

export default function Corpus() {
  const { isStaff } = useAuth();
  const [form, setForm] = useState(emptyFilters);
  const [applied, setApplied] = useState(emptyFilters);
  const [confirmingDeletePhaseRun, setConfirmingDeletePhaseRun] = useState(false);
  const deletePhaseRun = useDeletePhaseRun();

  function handleApply(event) {
    event.preventDefault();
    setApplied(form);
  }

  function handleClear() {
    setForm(emptyFilters);
    setApplied(emptyFilters);
  }

  const systemsQuery = useSystemDescriptions(buildParams(applied, { includeSystem: false }));
  const scenariosQuery = useScenarios(buildParams(applied, { includeSystem: true }));

  const phaseRunId = applied.phaseRun ? Number(applied.phaseRun) : null;
  const phaseRunQuery = usePhaseRun(phaseRunId);

  // Iterate-mode phase runs are ad-hoc: `pipeline_run` is null (spec §5.4).
  // Corpus rows now carry their own `is_scratch` directly (task 10.5, see
  // `ScratchBadge`/`SCRATCH_READONLY_NOTE` above), so this banner is no
  // longer the only way to learn a filtered view is scratch material - but
  // it is still the one place this screen can say so even when the
  // `?phase_run=` filter matches NO rows yet (an iterate run that hasn't
  // generated anything, or generated nothing matching the other filters),
  // and it is what backs the delete-this-run action below.
  const isScratch = phaseRunId != null && phaseRunQuery.isSuccess && phaseRunQuery.data.pipeline_run == null;

  const systems = systemsQuery.data?.results ?? [];
  const scenarios = scenariosQuery.data?.results ?? [];
  const systemTitleById = new Map(systems.map((system) => [system.id, system.title]));

  async function handleDeletePhaseRunConfirmed() {
    try {
      await deletePhaseRun.mutateAsync(phaseRunId);
      setConfirmingDeletePhaseRun(false);
      // The filter named a phase run that no longer exists - clear it
      // rather than leave the form pointed at a dangling id.
      setForm((current) => ({ ...current, phaseRun: '' }));
      setApplied((current) => ({ ...current, phaseRun: '' }));
    } catch {
      // Surfaced below via deletePhaseRun.isError/error - dialog stays open
      // so the API's own 409 message (e.g. "run_in_flight") is visible.
    }
  }

  return (
    <div className="space-y-8">
      <div>
        <h1 className="text-2xl font-semibold text-gray-900">Corpus</h1>
        <p className="mt-1 text-sm text-gray-500">
          System descriptions and scenarios, seed and generated alike. Seed and manual rows are
          editable; generated rows are the record of what a run produced and are read-only.
        </p>
      </div>

      <form
        onSubmit={handleApply}
        aria-label="Corpus filters"
        className="grid grid-cols-2 gap-3 rounded-lg border border-gray-200 bg-white p-4 sm:grid-cols-3 lg:grid-cols-6"
      >
        <div>
          <label htmlFor="filter-origin" className="block text-xs font-medium text-gray-700">
            Origin
          </label>
          <select
            id="filter-origin"
            value={form.origin}
            onChange={(event) => setForm((current) => ({ ...current, origin: event.target.value }))}
            className="mt-1 block w-full rounded-md border border-gray-300 px-2 py-1.5 text-sm shadow-sm"
          >
            <option value="">All origins</option>
            <option value="seed">Seed</option>
            <option value="generated">Generated</option>
            <option value="manual">Manual</option>
          </select>
        </div>
        <div>
          <label htmlFor="filter-run" className="block text-xs font-medium text-gray-700">
            Run (repetition id)
          </label>
          <input
            id="filter-run"
            type="number"
            value={form.run}
            onChange={(event) => setForm((current) => ({ ...current, run: event.target.value }))}
            className="mt-1 block w-full rounded-md border border-gray-300 px-2 py-1.5 text-sm shadow-sm"
          />
        </div>
        <div>
          <label htmlFor="filter-variant" className="block text-xs font-medium text-gray-700">
            Variant
          </label>
          <select
            id="filter-variant"
            value={form.variant}
            onChange={(event) => setForm((current) => ({ ...current, variant: event.target.value }))}
            className="mt-1 block w-full rounded-md border border-gray-300 px-2 py-1.5 text-sm shadow-sm"
          >
            <option value="">All variants</option>
            <option value="A">A</option>
            <option value="B">B</option>
          </select>
        </div>
        <div>
          <label htmlFor="filter-phase-run" className="block text-xs font-medium text-gray-700">
            Phase run id
          </label>
          <input
            id="filter-phase-run"
            type="number"
            value={form.phaseRun}
            onChange={(event) => setForm((current) => ({ ...current, phaseRun: event.target.value }))}
            className="mt-1 block w-full rounded-md border border-gray-300 px-2 py-1.5 text-sm shadow-sm"
          />
        </div>
        <div>
          <label htmlFor="filter-system" className="block text-xs font-medium text-gray-700">
            System id (scenarios)
          </label>
          <input
            id="filter-system"
            type="number"
            value={form.system}
            onChange={(event) => setForm((current) => ({ ...current, system: event.target.value }))}
            className="mt-1 block w-full rounded-md border border-gray-300 px-2 py-1.5 text-sm shadow-sm"
          />
        </div>
        <div className="flex items-end gap-2">
          <button
            type="submit"
            className="rounded-md bg-brand-600 px-3 py-1.5 text-sm font-medium text-white hover:bg-brand-700"
          >
            Apply filters
          </button>
          <button
            type="button"
            onClick={handleClear}
            className="rounded-md border border-gray-300 px-3 py-1.5 text-sm font-medium text-gray-700 hover:bg-gray-100"
          >
            Clear
          </button>
        </div>
      </form>

      {phaseRunId != null && phaseRunQuery.isError && <ErrorBanner error={phaseRunQuery.error} />}
      {isScratch && (
        <div className="space-y-3">
          <div role="status" className="rounded-md border border-amber-300 bg-amber-50 px-4 py-3 text-sm text-amber-800">
            Phase run #{phaseRunId} is an iterate-mode run: this material is scratch. It is never
            archived and never appears in an export.
          </div>
          {isStaff && !confirmingDeletePhaseRun && (
            <button
              type="button"
              onClick={() => setConfirmingDeletePhaseRun(true)}
              className="rounded-md border border-red-600 px-3 py-1.5 text-sm font-medium text-red-700 hover:bg-red-50"
            >
              Delete this run
            </button>
          )}
          {confirmingDeletePhaseRun && (
            <ConfirmDialog
              title={`Delete iterate run #${phaseRunId}?`}
              message="Its generated material — every system description and scenario it produced — goes with it. There is no per-row undo."
              confirmLabel="Confirm"
              cancelLabel="Never mind"
              pending={deletePhaseRun.isPending}
              onConfirm={handleDeletePhaseRunConfirmed}
              onCancel={() => setConfirmingDeletePhaseRun(false)}
            />
          )}
          {deletePhaseRun.isError && <ErrorBanner error={deletePhaseRun.error} />}
        </div>
      )}

      <section aria-labelledby="systems-heading" className="space-y-3">
        <h2 id="systems-heading" className="text-lg font-medium text-gray-900">
          System descriptions
        </h2>

        {systemsQuery.isLoading && <p className="text-sm text-gray-500">Loading system descriptions…</p>}
        {systemsQuery.isError && <ErrorBanner error={systemsQuery.error} />}

        {systemsQuery.isSuccess && systems.length === 0 && (
          <EmptyState title="No system descriptions match" message="Try clearing or widening the filters above." />
        )}

        {systemsQuery.isSuccess && systems.length > 0 && (
          <ul className="divide-y divide-gray-200 rounded-lg border border-gray-200 bg-white">
            {systems.map((system) => (
              <SystemDescriptionRow key={system.id} system={system} />
            ))}
          </ul>
        )}
      </section>

      <section aria-labelledby="scenarios-heading" className="space-y-3">
        <h2 id="scenarios-heading" className="text-lg font-medium text-gray-900">
          Scenarios
        </h2>

        {scenariosQuery.isLoading && <p className="text-sm text-gray-500">Loading scenarios…</p>}
        {scenariosQuery.isError && <ErrorBanner error={scenariosQuery.error} />}

        {scenariosQuery.isSuccess && scenarios.length === 0 && (
          <EmptyState title="No scenarios match" message="Try clearing or widening the filters above." />
        )}

        {scenariosQuery.isSuccess && scenarios.length > 0 && (
          <ul className="divide-y divide-gray-200 rounded-lg border border-gray-200 bg-white">
            {scenarios.map((scenario) => (
              <ScenarioRow
                key={scenario.id}
                scenario={scenario}
                systemTitle={systemTitleById.get(scenario.system_description) ?? `System #${scenario.system_description}`}
              />
            ))}
          </ul>
        )}
      </section>
    </div>
  );
}
