import { useState } from 'react';
import { useAllLabels, useScenarios, useSystemDescriptions } from '../api/queries';
import CollapsibleText from './CollapsibleText';
import ErrorBanner from './ErrorBanner';
import Modal from './Modal';

const CARD_FIELDS = [
  ['actor', 'Actor'],
  ['trigger', 'Trigger'],
  ['standing_state', 'Standing state'],
  ['asset', 'Asset'],
  ['threat', 'Threat'],
  ['outcome', 'Outcome'],
];

function ScenarioTabs({ scenarios }) {
  const [activeId, setActiveId] = useState(null);
  const active = scenarios.find((scenario) => scenario.id === activeId) ?? scenarios[0];
  if (!active) return <p className="text-xs text-gray-500">No scenarios for this system.</p>;

  return (
    <div className="space-y-2">
      <div role="tablist" className="flex flex-wrap gap-1 border-b border-gray-200">
        {scenarios.map((scenario) => (
          <button
            key={scenario.id}
            type="button"
            role="tab"
            aria-selected={scenario.id === active.id}
            onClick={() => setActiveId(scenario.id)}
            className={`-mb-px border-b-2 px-2 pb-1 text-xs font-medium ${
              scenario.id === active.id
                ? 'border-brand-600 text-brand-700'
                : 'border-transparent text-gray-500 hover:text-gray-900'
            }`}
          >
            {scenario.scenario_id}
          </button>
        ))}
      </div>
      <dl role="tabpanel" className="space-y-2 text-xs">
        {CARD_FIELDS.map(([field, label]) => (
          <div key={field}>
            <dt className="font-medium text-gray-500">{label}</dt>
            <dd className="whitespace-pre-wrap text-gray-800">{active[field] || '—'}</dd>
          </div>
        ))}
        <div>
          <dt className="font-medium text-gray-500">Narrative</dt>
          <dd className="whitespace-pre-wrap text-gray-800">{active.narrative || '—'}</dd>
        </div>
      </dl>
    </div>
  );
}

function GenerationView({ phaseRunId, wide }) {
  const scenariosQuery = useScenarios({ phase_run: phaseRunId });
  // All systems, not only generated ones: scenarios written against a target
  // system belong to a seed or manual row.
  const systemsQuery = useSystemDescriptions();
  const [selectedSystemId, setSelectedSystemId] = useState(null);

  if (scenariosQuery.isLoading || systemsQuery.isLoading) {
    return <p className="text-xs text-gray-500">Loading the saved output…</p>;
  }
  if (scenariosQuery.isError) return <ErrorBanner error={scenariosQuery.error} />;
  if (systemsQuery.isError) return <ErrorBanner error={systemsQuery.error} />;

  const scenarios = scenariosQuery.data?.results ?? [];
  const allSystems = systemsQuery.data?.results ?? [];
  const systemIds = new Set(scenarios.map((scenario) => scenario.system_description));
  const systems = allSystems.filter(
    (system) => system.generation_run === phaseRunId || systemIds.has(system.id)
  );
  if (systems.length === 0) {
    return <p className="text-xs text-gray-500">This run saved no systems or scenarios.</p>;
  }
  const selected = systems.find((system) => system.id === selectedSystemId) ?? systems[0];
  const selectedScenarios = scenarios.filter((scenario) => scenario.system_description === selected.id);

  return (
    <div className={`grid gap-3 ${wide ? 'grid-cols-1 md:grid-cols-[minmax(0,2fr)_minmax(0,3fr)]' : 'grid-cols-1'}`}>
      <div className="space-y-2">
        <p className="text-xs font-medium uppercase tracking-wide text-gray-500">
          {systems.length === 1 ? 'System' : `Systems (${systems.length})`}
        </p>
        {systems.length > 1 && (
          <div className="flex flex-wrap gap-1">
            {systems.map((system) => (
              <button
                key={system.id}
                type="button"
                aria-pressed={system.id === selected.id}
                onClick={() => setSelectedSystemId(system.id)}
                className={`rounded-md border px-2 py-0.5 text-xs ${
                  system.id === selected.id
                    ? 'border-brand-600 bg-brand-50 text-brand-700'
                    : 'border-gray-300 text-gray-700 hover:bg-gray-100'
                }`}
              >
                {system.title}
              </button>
            ))}
          </div>
        )}
        <div className="rounded-md border border-gray-200 p-2">
          <p className="text-sm font-semibold text-gray-900">{selected.title}</p>
          {selected.generation_run !== phaseRunId && (
            <p className="text-xs text-gray-500">Target system (not generated by this run)</p>
          )}
          <div className="mt-1">
            <CollapsibleText text={selected.body} empty="(no body)" mono={false} />
          </div>
        </div>
      </div>
      <div className="space-y-2">
        <p className="text-xs font-medium uppercase tracking-wide text-gray-500">
          Scenarios ({selectedScenarios.length})
        </p>
        <ScenarioTabs key={selected.id} scenarios={selectedScenarios} />
      </div>
    </div>
  );
}

function LabellingView({ phaseRunId, callId }) {
  const labelsQuery = useAllLabels({ phase_run: phaseRunId });
  if (labelsQuery.isLoading) return <p className="text-xs text-gray-500">Loading the saved labels…</p>;
  if (labelsQuery.isError) return <ErrorBanner error={labelsQuery.error} />;
  const labels = (labelsQuery.data?.results ?? []).filter((label) => label.llm_call === callId);
  if (labels.length === 0) {
    return <p className="text-xs text-gray-500">No labels: the model found none of the vulnerabilities in this scenario.</p>;
  }
  return (
    <ul className="space-y-2 text-xs">
      {labels.map((label) => (
        <li key={label.id} className="rounded-md border border-gray-200 p-2">
          <p className="font-semibold text-gray-900">
            {label.hcv_id} — {label.hcv_name}{' '}
            <span className="font-normal text-gray-500">({label.scenario_id})</span>
          </p>
          <p className="mt-1 text-gray-700">
            <span className="font-medium text-gray-500">Evidence: </span>
            {label.evidence || '—'}
          </p>
          <p className="text-gray-700">
            <span className="font-medium text-gray-500">Rationale: </span>
            {label.rationale || '—'}
          </p>
        </li>
      ))}
    </ul>
  );
}

// What the pipeline saved from one call's reply: generated systems with their
// scenarios as tabs (phase 2), or the labels (phase 3). Reads the stored rows,
// so it shows exactly what an experiment would keep.
export default function ParsedOutput({ phase, phaseRunId, call }) {
  const [expanded, setExpanded] = useState(false);

  if (!call.parsed_ok) {
    return (
      <p className="text-xs text-gray-500">
        Nothing was saved because the reply could not be parsed. See Raw response below.
      </p>
    );
  }

  const content = (wide) =>
    phase === 3 ? (
      <LabellingView phaseRunId={phaseRunId} callId={call.id} />
    ) : (
      <GenerationView phaseRunId={phaseRunId} wide={wide} />
    );

  return (
    <div className="space-y-2">
      <div className="flex justify-end">
        <button
          type="button"
          onClick={() => setExpanded(true)}
          className="rounded border border-gray-300 px-2 py-0.5 text-xs font-medium text-gray-700 hover:bg-gray-100"
        >
          Expand
        </button>
      </div>
      {content(false)}
      {expanded && (
        <Modal title="Parsed output" onClose={() => setExpanded(false)} wide>
          {content(true)}
        </Modal>
      )}
    </div>
  );
}
