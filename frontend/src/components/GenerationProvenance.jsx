import { useState } from 'react';
import { Link } from 'react-router-dom';
import { useQuery } from '@tanstack/react-query';
import { apiClient } from '../api/client';
import {
  queryKeys,
  useExperiment,
  usePhaseRun,
  usePhaseRunCalls,
  usePipelineRun,
  useTaxonomies,
} from '../api/queries';
import CodeBlock from './CodeBlock';
import ErrorBanner from './ErrorBanner';
import Modal from './Modal';
import StatusBadge from './StatusBadge';

function usePromptTemplate(id) {
  return useQuery({
    queryKey: queryKeys.prompts.detail(id),
    queryFn: async () => (await apiClient.get(`/prompts/${id}/`)).data,
    enabled: id != null,
  });
}

function Row({ label, children }) {
  return (
    <div>
      <dt className="text-xs font-medium text-gray-500">{label}</dt>
      <dd className="text-sm text-gray-800">{children}</dd>
    </div>
  );
}

function Disclosure({ title, children }) {
  const [open, setOpen] = useState(false);
  return (
    <div className="rounded-md border border-gray-200">
      <button
        type="button"
        onClick={() => setOpen((current) => !current)}
        aria-expanded={open}
        className="flex w-full items-center justify-between px-3 py-1.5 text-left text-xs font-medium text-gray-700 hover:bg-gray-50"
      >
        <span>{title}</span>
        <span className="text-gray-400">{open ? 'Hide' : 'Show'}</span>
      </button>
      {open && <div className="space-y-2 border-t border-gray-200 p-2">{children}</div>}
    </div>
  );
}

function ProvenanceDetails({ phaseRunId }) {
  const phaseRunQuery = usePhaseRun(phaseRunId);
  const phaseRun = phaseRunQuery.data;
  const promptQuery = usePromptTemplate(phaseRun?.prompt_template ?? null);
  const pipelineRunQuery = usePipelineRun(phaseRun?.pipeline_run ?? null);
  const pipelineRun = pipelineRunQuery.data;
  const experimentId = pipelineRun?.experiment ?? phaseRun?.experiment ?? null;
  const experimentQuery = useExperiment(experimentId, { enabled: experimentId != null });
  const taxonomiesQuery = useTaxonomies();
  const callsQuery = usePhaseRunCalls(phaseRunId);

  if (phaseRunQuery.isLoading) return <p className="text-sm text-gray-500">Loading…</p>;
  if (phaseRunQuery.isError) return <ErrorBanner error={phaseRunQuery.error} />;
  if (!phaseRun) return null;

  const prompt = promptQuery.data;
  const taxonomy = (taxonomiesQuery.data?.results ?? []).find((row) => row.id === phaseRun.taxonomy);
  const pinned = pipelineRun?.config;
  const counts = pinned
    ? [pinned.n_systems, pinned.n_scenarios_per_system]
    : [phaseRun.n_systems, phaseRun.n_scenarios_per_system];
  const calls = callsQuery.data?.results ?? [];

  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-center gap-2 text-sm text-gray-700">
        <StatusBadge status={phaseRun.status} />
        {phaseRun.pipeline_run ? (
          <span>
            Generated by{' '}
            <Link to={`/pipeline-runs/${phaseRun.pipeline_run}`} className="font-medium text-brand-700 hover:underline">
              repetition {pipelineRun?.repetition_index ?? '…'}
            </Link>{' '}
            of experiment{' '}
            {experimentId ? (
              <Link to={`/experiments/${experimentId}`} className="font-medium text-brand-700 hover:underline">
                {experimentQuery.data?.name ?? `#${experimentId}`}
              </Link>
            ) : (
              '—'
            )}
          </span>
        ) : (
          <span>
            Generated by a prompt test
            {experimentId && (
              <>
                {' '}
                borrowing the inputs of{' '}
                <Link to={`/experiments/${experimentId}`} className="font-medium text-brand-700 hover:underline">
                  {experimentQuery.data?.name ?? `#${experimentId}`}
                </Link>
              </>
            )}
          </span>
        )}
      </div>

      <dl className="grid grid-cols-1 gap-3 sm:grid-cols-2">
        <Row label="Prompt">
          {prompt ? (
            <Link to={`/prompts/${prompt.id}`} className="font-medium text-brand-700 hover:underline">
              {prompt.name} v{prompt.version}
            </Link>
          ) : (
            `#${phaseRun.prompt_template}`
          )}
        </Row>
        <Row label="Variant">{phaseRun.variant ? `Variant ${phaseRun.variant}` : '—'}</Row>
        <Row label="Model">
          {phaseRun.model}{' '}
          <a
            href={`https://openrouter.ai/${phaseRun.model}`}
            target="_blank"
            rel="noreferrer"
            className="text-xs text-brand-700 hover:underline"
          >
            OpenRouter ↗
          </a>
        </Row>
        <Row label="Temperature">{phaseRun.temperature}</Row>
        <Row label="Taxonomy">
          {taxonomy ? `${taxonomy.vocabulary_id} v${taxonomy.version}` : `#${phaseRun.taxonomy}`}
          {phaseRun.variant === 'A' && ' (used only to check the prompt; never shown to the model)'}
        </Row>
        <Row label="Counts requested">
          {counts[0] != null && counts[1] != null ? `${counts[0]} × ${counts[1]}` : 'built-in defaults'}
        </Row>
        {pinned && (
          <>
            <Row label="Seed systems">
              {(pinned.seed_systems ?? []).map((system) => system.title).join(', ') || '(none)'}
            </Row>
            <Row label="Few-shots">
              {(pinned.fewshots ?? []).map((fewshot) => fewshot.name).join(', ') || '(none)'}
            </Row>
          </>
        )}
        <Row label="Finished">{phaseRun.finished_at ? new Date(phaseRun.finished_at).toLocaleString() : '—'}</Row>
      </dl>

      {callsQuery.isError && <ErrorBanner error={callsQuery.error} />}
      {calls.map((call) => (
        <div key={call.id} className="space-y-2">
          <p className="text-xs text-gray-500">
            Call #{call.sequence} · {call.prompt_tokens ?? '—'} → {call.completion_tokens ?? '—'} tokens · $
            {Number(call.cost ?? 0).toFixed(4)} · finish: {call.finish_reason || '—'}
          </p>
          <Disclosure title="Exact prompt sent">
            <CodeBlock title="Rendered system prompt" code={call.rendered_system_prompt} />
            <CodeBlock title="Rendered user prompt" code={call.rendered_user_prompt} />
          </Disclosure>
          <Disclosure title="Raw response">
            <CodeBlock title="Raw response" code={call.raw_response} />
          </Disclosure>
        </div>
      ))}
    </div>
  );
}

// "How was this generated?" for a generated system or scenario: the run, prompt
// version, model and inputs behind it, plus the exact prompt sent.
export default function GenerationProvenance({ phaseRunId }) {
  const [open, setOpen] = useState(false);
  if (phaseRunId == null) return null;
  return (
    <>
      <button
        type="button"
        onClick={() => setOpen(true)}
        className="rounded-md border border-gray-300 px-2 py-1 text-xs font-medium text-gray-700 hover:bg-gray-100"
      >
        How was this generated?
      </button>
      {open && (
        <Modal title="How this was generated" onClose={() => setOpen(false)} wide>
          <ProvenanceDetails phaseRunId={phaseRunId} />
        </Modal>
      )}
    </>
  );
}
