import { describe, expect, it } from 'vitest';
import { extractErrorMessage, extractFieldErrors, hasNonFieldError } from '../errors';

// extractErrorMessage is the one place every DRF error shape this API can
// produce gets turned into a string (see the module's own comment). Each
// case here is a real shape a real view in this backend actually returns,
// not a hypothetical.
describe('extractErrorMessage', () => {
  it('falls back to the network error message when there is no response at all', () => {
    expect(extractErrorMessage({ message: 'Network Error' })).toBe('Network Error');
  });

  it('falls back to the given default when there is nothing usable at all', () => {
    expect(extractErrorMessage({}, 'default text')).toBe('default text');
  });

  it('reads a permission/auth failure shape: {"detail": "..."}', () => {
    const error = { response: { data: { detail: 'Authentication credentials were not provided.' } } };
    expect(extractErrorMessage(error)).toBe('Authentication credentials were not provided.');
  });

  it('reads a whole-serializer validation error: {"non_field_errors": [...]}', () => {
    const error = { response: { data: { non_field_errors: ['Invalid email or password.'] } } };
    expect(extractErrorMessage(error)).toBe('Invalid email or password.');
  });

  it('reads a field-level validation error: {"<field>": [...]}', () => {
    const error = { response: { data: { current_password: ['Current password is incorrect.'] } } };
    expect(extractErrorMessage(error)).toBe('Current password is incorrect.');
  });

  // corpus.views.ResourceFileViewSet.perform_destroy raises
  // ValidationError(f"'{name}' is still referenced by: ...") - a PLAIN
  // STRING, not a dict. DRF's ValidationError still coerces that into a
  // list internally, and the exception handler returns that list as the
  // ENTIRE response body (verified directly against
  // rest_framework.views.exception_handler's source: `isinstance(exc.detail,
  // (list, dict))` short-circuits straight to `data = exc.detail`, so the
  // body is `["'oldsmar-scenarios' is still referenced by: ..."]`, never
  // `{"detail": "..."}`). Before the fix this landed on the generic
  // fallback instead of the server's real refusal message.
  it('reads a bare top-level list of strings - a plain-string ValidationError, not a dict', () => {
    const error = {
      response: {
        data: ["'oldsmar-scenarios' is still referenced by: oldsmar. Remove or repoint those first."],
      },
    };
    expect(extractErrorMessage(error)).toBe(
      "'oldsmar-scenarios' is still referenced by: oldsmar. Remove or repoint those first."
    );
  });

  it('falls back to the default for an empty list, rather than crashing', () => {
    const error = { response: { data: [] } };
    expect(extractErrorMessage(error, 'default text')).toBe('default text');
  });
});

// Task 6's own acceptance bar: "surfaces the API's validation errors
// field-by-field ... each must land on the right field, not in a generic
// banner." These mirror the exact shape Experiment.clean() raises
// (backend/pipeline/models.py, via ExperimentSerializer.validate -
// pipeline/serializers.py), not a hypothetical one.
describe('extractFieldErrors', () => {
  it('maps a multi-field ValidationError onto its individual fields', () => {
    const error = {
      response: {
        data: {
          seed_systems: ["['Oldsmar'] were generated by a previous run. Seeding an experiment with its own output contaminates the comparison."],
          generate_systems: ['Enable at least one of generate_systems or generate_scenarios.'],
        },
      },
    };

    expect(extractFieldErrors(error)).toEqual({
      seed_systems: "['Oldsmar'] were generated by a previous run. Seeding an experiment with its own output contaminates the comparison.",
      generate_systems: 'Enable at least one of generate_systems or generate_scenarios.',
    });
  });

  it('joins a field carrying more than one message into one string', () => {
    const error = {
      response: {
        data: {
          variants: [
            'Unknown variant(s) [\'C\']; expected A and/or B.',
            "Duplicate variant(s) ['A']; each variant may appear at most once.",
          ],
        },
      },
    };

    const result = extractFieldErrors(error);
    expect(result.variants).toContain('Unknown variant');
    expect(result.variants).toContain('Duplicate variant');
  });

  it('excludes detail, non_field_errors and code - those are not field errors', () => {
    const error = {
      response: {
        data: {
          detail: 'Something else entirely.',
          non_field_errors: ['A whole-serializer problem.'],
          code: 'some_code',
          taxonomy: ['This taxonomy has no HCV rows.'],
        },
      },
    };

    expect(extractFieldErrors(error)).toEqual({ taxonomy: 'This taxonomy has no HCV rows.' });
  });

  it('returns an empty map for a non-field body (a plain string, a bare list, or nothing at all)', () => {
    expect(extractFieldErrors({ response: { data: 'plain string' } })).toEqual({});
    expect(extractFieldErrors({ response: { data: ['a', 'b'] } })).toEqual({});
    expect(extractFieldErrors({})).toEqual({});
  });
});

describe('hasNonFieldError', () => {
  it('is true for a detail-shaped error (a 503, a permission failure)', () => {
    expect(hasNonFieldError({ response: { data: { detail: 'No API key.' } } })).toBe(true);
  });

  it('is true for a non_field_errors-shaped error', () => {
    expect(hasNonFieldError({ response: { data: { non_field_errors: ['Bad login.'] } } })).toBe(true);
  });

  it('is false once every key in the body is a specific field', () => {
    expect(
      hasNonFieldError({ response: { data: { seed_systems: ['x'], generate_systems: ['y'] } } })
    ).toBe(false);
  });

  it('is true for a network error carrying no response body at all', () => {
    expect(hasNonFieldError({ message: 'Network Error' })).toBe(true);
  });
});
