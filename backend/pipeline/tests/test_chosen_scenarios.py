def _body(phase3_template, taxonomy, **overrides):
    body = {
        "phase": 3,
        "model": "m3",
        "prompt_template": phase3_template.pk,
        "taxonomy": taxonomy.pk,
    }
    body.update(overrides)
    return body


def _post(api_client, staff, body):
    api_client.force_authenticate(user=staff)
    with patch("pipeline.orchestration.async_task") as enqueued:
        response = api_client.post("/api/phase-runs/", body, format="json")
    return response, enqueued


@pytest.mark.django_db
def test_a_mixed_choice_labels_exactly_those_scenarios_end_to_end(
    api_client, staff, taxonomy, phase3_template, corpus, _client
):
    chosen = [corpus[0], corpus[3]]  # one seed, one generated
    _client.queue(LABELLED)
    _client.queue(LABELLED)

    response, enqueued = _post(
        api_client,
        staff,
        _body(phase3_template, taxonomy, scenarios=[s.pk for s in chosen]),
    )

    assert response.status_code == 202, response.json()
    assert response.json()["scenarios"] == [s.pk for s in chosen]
    assert response.json()["source_phase_run"] is None
    _, queued_pk = enqueued.call_args.args
    assert run_phase3_task(queued_pk) == PhaseRun.Status.COMPLETED

    run = PhaseRun.objects.get(pk=queued_pk)
    assert run.total_children == 2
    assert run.completed_children == 2
    assert set(Label.objects.filter(phase_run=run).values_list("scenario_id", flat=True)) == {
        s.pk for s in chosen
    }
    assert len(_client.calls) == 2


@pytest.mark.django_db
def test_duplicate_ids_are_labelled_once(api_client, staff, taxonomy, phase3_template, corpus):
    response, _ = _post(
        api_client,
        staff,
        _body(phase3_template, taxonomy, scenarios=[corpus[1].pk, corpus[1].pk]),
    )
    assert response.status_code == 202
    assert PhaseRun.objects.get(phase=3).scenario_ids == [corpus[1].pk]


@pytest.mark.django_db
@pytest.mark.parametrize(
    "scenarios_value, fragment",
    [
        ([], "at least one"),
        ([999_999], "no longer exist"),
    ],
)
def test_an_empty_or_unknown_choice_is_refused(
    api_client, staff, taxonomy, phase3_template, corpus, scenarios_value, fragment
):
    response, enqueued = _post(
        api_client, staff, _body(phase3_template, taxonomy, scenarios=scenarios_value)
    )
    assert response.status_code == 400
    assert fragment in str(response.json()["scenarios"])
    assert PhaseRun.objects.count() == 1  # only the `generation` fixture
    assert enqueued.call_count == 0


