@pytest.mark.django_db
def test_a_run_whose_chosen_scenarios_were_all_deleted_fails_not_labels_everything(
    taxonomy, phase3_template, corpus
):
    run = PhaseRun.objects.create(
        phase=3,
        model="m3",
        prompt_template=phase3_template,
        taxonomy=taxonomy,
        scenario_ids=[corpus[0].pk],
    )
    corpus[0].delete()

    assert list(scenarios_for(run)) == []
    finished = finish_labelling_run(run)
    assert finished.status == PhaseRun.Status.FAILED
    assert "deleted" in finished.error


@pytest.mark.django_db
def test_the_database_refuses_a_choice_on_a_generation_run(taxonomy, phase3_template):
    experiment = Experiment.objects.create(
        name="e",
        taxonomy=taxonomy,
        phase2_model="m2",
        phase2_prompt_a=phase3_template,
        phase2_prompt_b=phase3_template,
        phase3_model="m3",
        phase3_prompt=phase3_template,
    )
    pipeline_run = PipelineRun.objects.create(experiment=experiment, repetition_index=1)
    with pytest.raises(IntegrityError):
        PhaseRun.objects.create(
            pipeline_run=pipeline_run,
            phase=2,
            variant="A",
            model="m3",
            prompt_template=phase3_template,
            taxonomy=taxonomy,
            scenario_ids=[1],
        )
