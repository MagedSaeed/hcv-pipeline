@pytest.mark.django_db
def test_an_empty_run_filter_is_treated_as_absent_not_a_500(api_client, member, corpus_runs):
    """`?run=` with no value reaches `integer_param` as `""`, which this
    codebase's shared helper (`core.params.integer_param`, already relied on
    by `?system=`, `?phase=`, `?experiment=`, `?pipeline_run=`) treats the
    same as the parameter being absent altogether — never a 500, and this is
    the SAME behaviour every other integer filter in this API already has
    for a blank value, not a special case invented for `run`. It is
    deliberately compared against the truly-unfiltered baseline here so a
    regression (a 500, or a different count) is caught either way.
    """
    api_client.force_authenticate(user=member)

    empty = api_client.get("/api/system-descriptions/?run=")
    unfiltered = api_client.get("/api/system-descriptions/")

    assert empty.status_code == 200
    assert empty.json()["count"] == unfiltered.json()["count"]


