"""`?variant=`, `?run=` and `?phase_run=` on `/api/system-descriptions/` and
`/api/scenarios/` — see `corpus.views.SystemDescriptionViewSet.get_queryset`
and `ScenarioViewSet.get_queryset`.

Every filter test here is built so it FAILS if the filter clause it exercises
is deleted from the view: each fixture row is excluded by at least one other
row that would wrongly be included by a no-op filter. This was verified by
hand — each clause was temporarily removed, the matching test re-run to
confirm it failed, then the clause restored (see the task report).
"""

