@pytest.mark.django_db
def test_system_description_list_does_not_n_plus_one_with_the_new_filters(
    api_client, member, corpus_runs
):
    """Filtering on `generation_run` must not turn the list into a per-row
    query. Both serializers now read `generation_run` per row too
    (`is_scratch`, task 10.5), which the viewsets' `select_related` pays for
    — see the unfiltered, distinct-run measurement below. Measured, not
    assumed."""
    api_client.force_authenticate(user=member)

    with CaptureQueriesContext(connection) as few:
        api_client.get("/api/system-descriptions/?variant=A")

    run_adhoc = corpus_runs["run_adhoc"]
    SystemDescription.objects.bulk_create(
        # `bulk_create` bypasses `SystemDescription.save()`, which is what
        # normally derives a unique `slug` from the title — without setting
        # one explicitly here, every row gets the same blank slug and trips
        # the unique constraint on the second insert.
        SystemDescription(
            title=f"Bulk system {index}",
            slug=f"bulk-system-{index}",
            origin=Origin.GENERATED,
            generation_run=run_adhoc,
        )
        for index in range(20)
    )

    with CaptureQueriesContext(connection) as many:
        api_client.get("/api/system-descriptions/?variant=A")

    assert len(many) == len(few)


